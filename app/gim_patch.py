def patch_decide_labels(data: bytes) -> bytes:
    patched = bytearray(data)
    for offset, rows in DECIDE_LABEL_MASKS:
        encoded = gim.encode_p4_swizzled(rows)
        patched[offset:offset + len(encoded)] = encoded
    return bytes(patched)
